"""
2026-10-12: GT Pull (Apps Script, GT_Pull/Realtime.js) appends approved GT lines to
Full Flow within ~1-2 min of approval, in the same row shape this job appends.

  1. contract: the row Realtime.js writes == the row write_full_flow writes for the same
     GT Pull FMS row with no Vinculum match (fixture generated by GT_Pull
     tests/realtime.test.js; keep both copies identical)
  2. such rows are "existing": find_new_fms_rows never appends them again
  3. their blank Vinculum columns are filled by the nightly fill like any existing row
  4. rows that reach Full Flow WHILE this job runs are not appended twice, and the grid is
     never shrunk under them
"""
import json
import os
import types

import pandas as pd
import pytest

FIXTURE = os.path.join(os.path.dirname(__file__), "fixtures", "full_flow_row_contract.json")


def _contract():
    with open(FIXTURE, encoding="utf-8") as f:
        return json.load(f)


class _Exec:
    def __init__(self, result=None, on_call=None):
        self.result, self.on_call = result, on_call

    def execute(self):
        if self.on_call:
            self.on_call()
        return self.result


class FakeSheets:
    """Records Sheets API calls made by read_fms_sheet / write_full_flow."""

    def __init__(self, get_values=None):
        self.get_values = get_values or []
        self.updates, self.batch = [], []

    def spreadsheets(self):
        return self

    def values(self):
        return self

    def get(self, **kw):
        return _Exec({"values": self.get_values})

    def update(self, **kw):
        return _Exec(on_call=lambda: self.updates.append(kw))

    def batchUpdate(self, **kw):
        return _Exec(on_call=lambda: self.batch.append(kw))


def _fms_df_as_read(ff, monkeypatch, form_received_display):
    """GT Pull FMS row -> fms_df exactly as read_fms_sheet() builds it."""
    c = _contract()
    row = list(c["fms_row"])
    row[0] = form_received_display                  # FORMATTED_STRING of the date cell
    fake = FakeSheets(get_values=[c["fms_headers"], row])
    monkeypatch.setattr(ff, "sheets_service", fake)
    return ff.read_fms_sheet()


@pytest.mark.parametrize("display", ["12-Oct-2026 12:05:00", "12/10/2026 12:05:00"])
def test_contract_apps_script_row_equals_nightly_row(ff, monkeypatch, display):
    c = _contract()
    fms_df = _fms_df_as_read(ff, monkeypatch, display)
    new_df = ff.build_full_flow(fms_df, [[]], {}, {"W1": "Vadape"}, [None])
    fake = FakeSheets()
    monkeypatch.setattr(ff, "sheets_service", fake)
    monkeypatch.setattr(ff, "get_sheet_by_title",
                        lambda *a: {"gridProperties": {"rowCount": 100}})
    ff.write_full_flow(123, new_df, start_row=c["sheet_row"])
    written = fake.updates[0]["body"]["values"][0]
    assert len(written) == len(ff.OUTPUT_COLUMNS) == len(c["full_flow_row"]) == 55
    for i, (py, js) in enumerate(zip(written, c["full_flow_row"])):
        py = "" if py is None else py
        assert py == js, f"column {ff.OUTPUT_COLUMNS[i]} ({i}): nightly {py!r} != Apps Script {js!r}"
    # same date formats: A, S, X, AV
    fmt_cols = sorted(r["repeatCell"]["range"]["startColumnIndex"]
                      for r in fake.batch[-1]["body"]["requests"])
    assert fmt_cols == [0, 18, 23, 47]


def _apps_script_row_as_read(ff):
    """The appended row as read_existing_full_flow() reads it back (formula -> value)."""
    c = _contract()
    row = list(c["full_flow_row"])
    row[ff.OUTPUT_COLUMNS.index("Open Qty")] = 30
    return dict(zip(ff.OUTPUT_COLUMNS, row))


def test_apps_script_rows_are_not_appended_again(ff, make):
    existing = make.existing([_apps_script_row_as_read(ff)])
    fms = pd.DataFrame([{c: "" for c in ff.FMS_COLUMNS}], columns=ff.FMS_COLUMNS)
    fms.loc[0, ["GT Number", "Vinculum SKU"]] = ["GT121026A1", "NMH801912LS"]
    new_gt, new_line = ff.find_new_fms_rows(fms, existing)
    assert not new_gt.any() and not new_line.any()
    # ... but another SKU of the same GT still is (gap-3 rule unchanged)
    fms.loc[1] = fms.loc[0]
    fms.loc[1, "Vinculum SKU"] = "OTHER_SKU"
    new_gt, new_line = ff.find_new_fms_rows(fms, existing)
    assert list(new_gt) == [False, False] and list(new_line) == [False, True]


def test_blank_vinculum_columns_of_apps_script_row_are_filled(ff, make):
    writes, stats = make.plan(
        [_apps_script_row_as_read(ff)],
        [{"Order No": "N89701", "ExtOrderNo": "GT121026A1", "SKU Code": "NMH801912LS",
          "Invoice No": "INV1", "Pick Qty": 30, "Total": 52746}])
    cells = make.cells(writes)
    assert cells[(8, "Order No")] == "N89701"
    assert cells[(8, "Team")] == "Gauri"
    assert cells[(8, "Invoice No")] == "INV1"
    assert cells[(8, "Invoice Amount")] == 52746
    assert cells[(8, "Warehouse")] == "Vadape"
    assert cells[(8, "Dispatched Qty")] == 30
    assert (8, "Actual") in cells
    # A:O and the customer block are never touched
    assert not any(c in ("GT Number", "Vinculum SKU", "Order Quantity", "Party Name")
                   for _, c in cells)


def test_apps_script_row_gets_order_no_from_daily_order_enquiry(ff, make):
    writes, stats = make.plan(
        [_apps_script_row_as_read(ff)], [],
        oe_rows=[{"Order No": "N89702", "ExtOrderNo": "GT121026A1"}])
    assert make.cells(writes)[(8, "Order No")] == "N89702"


def test_rows_that_arrived_during_the_run_are_dropped(ff, make):
    new_df = make.existing([
        {"GT Number": "GT121026A1", "Vinculum SKU": "NMH801912LS"},
        {"GT Number": "GT121026A2", "Vinculum SKU": "S2"},
    ])
    fresh = make.existing([{"GT Number": " gt121026a1", "Vinculum SKU": "nmh801912ls "}])
    kept, dropped = ff.drop_rows_now_in_full_flow(new_df, fresh)
    assert dropped == 1
    assert list(kept["GT Number"]) == ["GT121026A2"]
    kept, dropped = ff.drop_rows_now_in_full_flow(new_df, make.existing([]))
    assert dropped == 0 and len(kept) == 2


def test_grid_is_never_shrunk(ff, make, monkeypatch):
    assert ff.grid_row_count(9000, 8400) == 9000
    assert ff.grid_row_count(8300, 8400) == 8400
    fake = FakeSheets()
    monkeypatch.setattr(ff, "sheets_service", fake)
    monkeypatch.setattr(ff, "get_sheet_by_title",
                        lambda *a: {"gridProperties": {"rowCount": 9000}})
    ff.write_full_flow(1, make.existing([{"GT Number": "GT1", "Vinculum SKU": "S"}]),
                       start_row=8300)
    props = fake.batch[0]["body"]["requests"][0]["updateSheetProperties"]["properties"]
    assert props["gridProperties"]["rowCount"] == 9000
